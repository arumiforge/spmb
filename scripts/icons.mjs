// Copies the Lucide icons listed in resources/icons.json from node_modules/lucide-static
// into app/Helpers/lucide_icons.php, so production needs no Node (D-070).
// Run: node scripts/icons.mjs   (or npm run icons)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(readFileSync(join(root, 'resources/icons.json'), 'utf8'));
const lucideDir = join(root, 'node_modules/lucide-static');
const version = JSON.parse(readFileSync(join(lucideDir, 'package.json'), 'utf8')).version;

const php = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";
const icons = {};
const missing = [];

for (const name of [...new Set(manifest.icons)].sort()) {
    const file = join(lucideDir, 'icons', `${name}.svg`);
    if (!existsSync(file)) {
        missing.push(name);
        continue;
    }
    const svg = readFileSync(file, 'utf8');
    const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>'));
    icons[name] = inner
        .split('\n')
        .map((line) => line.trim())
        .filter(Boolean)
        .join('')
        .replace(/\s*\/>/g, '/>');
}

const aliases = Object.fromEntries(Object.entries(manifest.aliases).sort(([a], [b]) => a.localeCompare(b)));
for (const [alias, target] of Object.entries(aliases)) {
    if (!(target in icons)) {
        missing.push(`${target} (alias ${alias})`);
    }
}

if (missing.length > 0) {
    console.error(`Unknown Lucide icons: ${missing.join(', ')}`);
    process.exit(1);
}

const pad = (keys) => Math.max(...keys.map((k) => php(k).length));
const iconPad = pad(Object.keys(icons));
const aliasPad = pad(Object.keys(aliases));

const out = `<?php

declare(strict_types=1);

/**
 * Lucide icons (lucide-static ${version}, ISC licence, https://lucide.dev).
 * Generated by scripts/icons.mjs from resources/icons.json — do not edit by hand.
 * Used by icon() in ui_helper.php.
 *
 * @return array{icons: array<string, string>, aliases: array<string, string>}
 */
return [
    'icons' => [
${Object.entries(icons).map(([k, v]) => `        ${php(k).padEnd(iconPad)} => ${php(v)},`).join('\n')}
    ],
    'aliases' => [
${Object.entries(aliases).map(([k, v]) => `        ${php(k).padEnd(aliasPad)} => ${php(v)},`).join('\n')}
    ],
];
`;

writeFileSync(join(root, 'app/Helpers/lucide_icons.php'), out);
console.log(`Wrote ${Object.keys(icons).length} icons and ${Object.keys(aliases).length} aliases to app/Helpers/lucide_icons.php`);
